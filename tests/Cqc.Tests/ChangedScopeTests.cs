using Cqc.Core;
using Cqc.CSharp;
using Xunit;

namespace Cqc.Tests;

public sealed class ChangedScopeTests
{
    [Fact]
    public async Task SelectsEachUncommittedFileOnceAndAnalyzesWorkingTreeContent()
    {
        using var workspace = FixtureWorkspace.Empty();
        await Write(workspace, "Staged.cs", "class Staged {}");
        await Write(workspace, "Unstaged.cs", "class Unstaged {}");
        await Write(workspace, "Partial.cs", "class Before {}");
        await Write(workspace, "Context.cs", "class Context {}");
        await Initialize(workspace);
        await Write(workspace, "Staged.cs", "class Staged { int Value() => 1; }");
        await Write(workspace, "Partial.cs", "class IndexVersion {}");
        await workspace.Git("add", "Staged.cs", "Partial.cs");
        await Write(workspace, "Partial.cs", "class WorkingTree { int Latest() => 2; }");
        await Write(workspace, "Unstaged.cs", "class Unstaged { int Value() => 3; }");
        await Write(workspace, "New file.cs", "class NewFile {}");
        var snapshot = await workspace.Discover("changed");
        Assert.Equal(["New file.cs", "Partial.cs", "Staged.cs", "Unstaged.cs"], snapshot.SelectedFiles);
        Assert.Contains("Context.cs", snapshot.Files);
        var facts = await new CSharpAnalyzer().AnalyzeAsync(snapshot, CancellationToken.None);
        Assert.Contains(facts.Types, type => type.Id.Contains("WorkingTree", StringComparison.Ordinal));
        Assert.DoesNotContain(facts.Types, type => type.Id.Contains("IndexVersion", StringComparison.Ordinal));
        Assert.False(Directory.Exists(Path.Combine(workspace.Root, ".cqc")));
    }

    [Fact]
    public async Task CleanAndCommittedChangesRequireAnExplicitBase()
    {
        using var workspace = FixtureWorkspace.Empty();
        await Write(workspace, "Example.cs", "class Example {}");
        await Initialize(workspace);
        Assert.Empty((await workspace.Discover("changed")).SelectedFiles);
        await Write(workspace, "Example.cs", "class Example { int Value() => 1; }");
        await workspace.Git("add", ".");
        await Commit(workspace);
        Assert.Empty((await workspace.Discover("changed")).SelectedFiles);
        var snapshot = await Discover(workspace.Root, "HEAD~1");
        Assert.Equal(["Example.cs"], snapshot.SelectedFiles);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task DeletedFilesAreExcludedAndRenamesSelectTheirDestination(bool staged)
    {
        using var workspace = FixtureWorkspace.Empty();
        await Write(workspace, "Deleted.cs", "class Deleted {}");
        await Write(workspace, "Original.cs", "class Renamed {}");
        await Initialize(workspace);
        File.Delete(Path.Combine(workspace.Root, "Deleted.cs"));
        File.Move(Path.Combine(workspace.Root, "Original.cs"), Path.Combine(workspace.Root, "Renamed file.cs"));
        if (staged) await workspace.Git("add", "-A");
        Assert.Equal(["Renamed file.cs"], (await workspace.Discover("changed")).SelectedFiles);
    }

    [Fact]
    public async Task IgnoresGeneratedAndExcludedSources()
    {
        using var workspace = FixtureWorkspace.Empty();
        await Write(workspace, ".gitignore", "Ignored.cs\n");
        await Initialize(workspace);
        await Write(workspace, "Ignored.cs", "class Ignored {}");
        await Write(workspace, "Generated.g.cs", "class Generated {}");
        await Write(workspace, "Marked.cs", "// <auto-generated>\nclass Marked {}");
        await Write(workspace, "Configured.cs", "class Configured {}");
        await Write(workspace, "Visible.cs", "class Visible {}");
        var snapshot = await ProjectDiscovery.DiscoverAsync(new() { ProjectRoot = workspace.Root, Scope = "changed" },
            new() { Exclude = ["Configured.cs"] }, CancellationToken.None, FixtureWorkspace.Definitions);
        Assert.Equal(["Visible.cs"], snapshot.SelectedFiles);
    }

    [Fact]
    public async Task NestedProjectUsesProjectRelativePathsAndExcludesOutsideChanges()
    {
        using var workspace = FixtureWorkspace.Empty();
        Directory.CreateDirectory(Path.Combine(workspace.Root, "module"));
        await Write(workspace, "module/Staged.cs", "class Staged {}");
        await Write(workspace, "module/Unstaged.cs", "class Unstaged {}");
        await Write(workspace, "Outside.cs", "class Outside {}");
        await Initialize(workspace);
        await Write(workspace, "module/Staged.cs", "class Staged { int Value() => 1; }");
        await workspace.Git("add", "module/Staged.cs");
        await Write(workspace, "module/Unstaged.cs", "class Unstaged { int Value() => 2; }");
        await Write(workspace, "module/New file.cs", "class NewFile {}");
        await Write(workspace, "Outside.cs", "class Outside { int Value() => 3; }");
        var snapshot = await Discover(Path.Combine(workspace.Root, "module"));
        Assert.Equal(["New file.cs", "Staged.cs", "Unstaged.cs"], snapshot.SelectedFiles);
        Assert.DoesNotContain("Outside.cs", snapshot.Files);
    }

    internal static Task Write(FixtureWorkspace workspace, string path, string content) =>
        File.WriteAllTextAsync(Path.Combine(workspace.Root, path), content);

    internal static async Task Initialize(FixtureWorkspace workspace)
    {
        await workspace.Git("init", "-q");
        await workspace.Git("add", ".");
        await Commit(workspace);
    }

    private static Task Commit(FixtureWorkspace workspace) => workspace.Git("-c", "user.email=tests@example.invalid",
        "-c", "user.name=CQC Tests", "commit", "--allow-empty", "-qm", "fixture");

    private static Task<ProjectSnapshot> Discover(string root, string? gitBase = null) => ProjectDiscovery.DiscoverAsync(
        new() { ProjectRoot = root, Scope = "changed", GitBase = gitBase }, new(), CancellationToken.None, FixtureWorkspace.Definitions);
}
